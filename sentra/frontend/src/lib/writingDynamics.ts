/**
 * Writing dynamics, and their change against the student's own past (#468).
 *
 * ## Why this file exists
 *
 * blesc.jp says Blesc looks not at the text but at the change relative to the
 * student's own past — in wording, and in how they write: hesitating before
 * going on, writing something and taking it back. The educator mock shows a
 * 「書きぶりの変化」 observation.
 *
 * Until #468 none of the writing half of that ran where students write. The
 * analysis existed in `backend/app/analytics/writing_dynamics.py`, on the
 * FastAPI research path, which is local-only and not deployed (ADR 0001). The
 * Next.js production path collected the telemetry it reads — `telemetry.ts`,
 * stored by `supabaseWriter` into `entry_fields` and `interaction_events` — and
 * analysed none of it. The only observation an educator could see in
 * production was a deterministic safety-lexicon match.
 *
 * The owner chose option B: bring the analysis into production rather than
 * narrow the claim. This is a deliberate port, the same relationship
 * `baseline.ts` has with `baseline.py` and `safety-assessment.ts` with
 * `services/safety.py`. Both implementations are pinned to
 * `sentra/shared/writing_dynamics_conformance.json`, whose expected values are
 * generated by running the Python, so a divergence fails a build on either side
 * instead of reaching an educator.
 *
 * ## What this does NOT do
 *
 * - It reads timing and lengths. It never sees text; `telemetry.ts` never sends
 *   any, and `findLeakedText` is the test for that.
 * - It does not say what a change means. The output is "this entry's longest
 *   pause was longer than in this student's own recent writing days", and the
 *   educator surface renders that and stops. No score, no band, no inference
 *   about a state of mind (`docs/educator_display_policy.md`).
 * - It does not compare a student against anyone else, and below
 *   `RAMP_UP_DAYS` of their own qualifying days it does not compare at all —
 *   the same refusal the graph baseline makes (#91).
 */

import { RAMP_UP_DAYS, baselineProvenance, type BaselineProvenance } from "./baseline.ts";

export const PIPELINE_VERSION = "writing-dynamics-v1";
export const WRITING_CHANGE_VERSION = "writing-change-v1";

/**
 * The one field a baseline is kept for. The journal body is the only free-text
 * field written every day; `first_recall_30` is a timed probe whose length is
 * bounded by design, and `mood` / `event_categories` are selections.
 */
export const WRITING_CHANGE_FIELD = "journal_entry";

/**
 * The features compared against the student's own history. The reasons for
 * each, and for leaving out `revision_ratio` (identical to `pause_ratio` under
 * this collector) and `large_revision_count` (always zero under it), are next
 * to `WRITING_CHANGE_FEATURES` in `writing_dynamics.py`; the two lists are the
 * same list, which the contract test checks.
 */
export const WRITING_CHANGE_FEATURES = [
  "pause_ratio",
  "max_pause_ms",
  "deletion_ratio",
  "chars_per_minute",
  "final_length",
] as const;
export type WritingChangeFeature = (typeof WRITING_CHANGE_FEATURES)[number];

/** Fewer edits than this on the journal field: not compared, not counted. Engineering floor. */
export const MIN_FIELD_INPUTS = 5;

/**
 * |z| at or above which a feature is reported as a change.
 *
 * An engineering choice, and stated as one wherever it travels: nothing in this
 * repository has measured how often a student's writing moves two of their own
 * standard deviations on an ordinary day. Until that is measured this is "the
 * conventional line for unusual-for-this-person", not a validated threshold —
 * and the educator surface says "an observation", never "a finding".
 */
export const CHANGE_Z_THRESHOLD = 2.0;

/** Floor on the standard deviation, as in `estimateBaseline`. */
export const MIN_STD = 0.01;

/** The `pause_count` fallback in the Python, used only when field metrics carry none. */
const FALLBACK_PAUSE_GAP_MS = 1500;

export type WritingDynamicsEvent = {
  field_name?: unknown;
  event_type?: unknown;
  relative_ms?: unknown;
  value_length?: unknown;
  metadata?: unknown;
};

export type FieldDynamics = {
  pipeline_version: string;
  field_name: string;
  event_count: number;
  input_count: number;
  first_input_latency_ms: number | null;
  active_span_ms: number;
  final_length: number;
  chars_per_minute: number;
  inter_input_median_ms: number;
  inter_input_p90_ms: number;
  pause_count: number;
  max_pause_ms: number;
  pause_ratio: number;
  deletion_ratio: number;
  revision_ratio: number;
  large_revision_count: number;
  paste_count: number;
  focus_count: number;
  blur_count: number;
};

// ---------------------------------------------------------------------------
// Python semantics, reproduced
// ---------------------------------------------------------------------------

/**
 * Python's `int(x or 0)`.
 *
 * `or` falls through on every falsy value, so 0, "", null and a missing key all
 * become the fallback; `int()` truncates a float toward zero. A value Python
 * would raise on is treated as 0 — the port must not throw on a payload the
 * collector did not produce.
 */
function pyInt(value: unknown, fallback: number = 0): number {
  if (!value) return fallback;
  const numeric = typeof value === "number" ? value : Number(value);
  return Number.isFinite(numeric) ? Math.trunc(numeric) : fallback;
}

/** `int(a or b or c)` for the chains the Python writes. */
function pyIntOr(...values: unknown[]): number {
  for (const value of values) {
    if (value) return pyInt(value);
  }
  return 0;
}

function pyFloat(value: unknown): number {
  if (!value) return 0;
  const numeric = typeof value === "number" ? value : Number(value);
  return Number.isFinite(numeric) ? numeric : 0;
}

/**
 * Python's `round(x)` to an integer: half to even. `Math.round(4.5)` is 5; the
 * percentile index in `_percentile` is 4.
 */
function roundHalfEven(value: number): number {
  const floor = Math.floor(value);
  const diff = value - floor;
  if (diff > 0.5) return floor + 1;
  if (diff < 0.5) return floor;
  return floor % 2 === 0 ? floor : floor + 1;
}

/**
 * Python's `round(x, digits)`.
 *
 * Both Python and `toFixed` round the exact binary value of `x`, so they agree
 * everywhere except an exact tie, where Python goes to even and `toFixed` away
 * from zero. A double is an exact tie at `digits` decimals only when
 * `x * 2^(digits+1)` is an odd integer — a power-of-two multiply is exact, so
 * that test is too — and only then is the result corrected.
 */
export function pyRound(value: number, digits: number): number {
  if (!Number.isFinite(value)) return value;
  const magnitude = Math.abs(value);
  let rounded = Number(magnitude.toFixed(digits));
  const scaled = magnitude * 2 ** (digits + 1);
  if (Number.isInteger(scaled) && scaled % 2 === 1) {
    const unit = 10 ** digits;
    const lastDigits = Math.round(rounded * unit);
    if (lastDigits % 2 === 1) rounded = Number(((lastDigits - 1) / unit).toFixed(digits));
  }
  return value < 0 ? -rounded : rounded;
}

function safeRatio(numerator: number, denominator: number): number {
  return denominator ? pyRound(numerator / denominator, 6) : 0;
}

function percentile(values: number[], fraction: number): number {
  if (values.length === 0) return 0;
  const ordered = [...values].sort((a, b) => a - b);
  const index = Math.min(ordered.length - 1, Math.max(0, roundHalfEven((ordered.length - 1) * fraction)));
  return ordered[index];
}

/** `statistics.median`: the mean of the two middle values for an even count. */
function median(values: number[]): number {
  const ordered = [...values].sort((a, b) => a - b);
  const middle = Math.floor(ordered.length / 2);
  return ordered.length % 2 === 1 ? ordered[middle] : (ordered[middle - 1] + ordered[middle]) / 2;
}

function metadataDelta(event: WritingDynamicsEvent): number {
  const metadata = event.metadata;
  if (!metadata || typeof metadata !== "object") return 0;
  return Math.abs(pyInt((metadata as Record<string, unknown>).delta));
}

// ---------------------------------------------------------------------------
// Per-session dynamics: `writing_dynamics_for_field` / `_for_session`
// ---------------------------------------------------------------------------

export function writingDynamicsForField(
  fieldName: string,
  fieldMetrics: Record<string, unknown>,
  rawEvents: WritingDynamicsEvent[],
): FieldDynamics {
  // Array.prototype.sort is stable, as Python's sorted() is, so events with the
  // same relative_ms keep their arrival order on both sides.
  const events = rawEvents
    .filter((event) => event?.field_name === fieldName)
    .sort((a, b) => pyInt(a.relative_ms) - pyInt(b.relative_ms));
  const inputEvents = events.filter((event) => event.event_type === "input");
  const inputTimes = inputEvents.map((event) => pyInt(event.relative_ms));
  const intervals: number[] = [];
  for (let index = 1; index < inputTimes.length; index += 1) {
    const gap = inputTimes[index] - inputTimes[index - 1];
    if (gap >= 0) intervals.push(gap);
  }
  const largeJumps = inputEvents.map(metadataDelta).filter((delta) => delta > 1);

  const finalLength = inputEvents.length
    ? pyIntOr(inputEvents[inputEvents.length - 1].value_length, fieldMetrics.char_count)
    : 0;
  const firstInputMs = inputTimes.length ? inputTimes[0] : null;
  const lastInputMs = inputTimes.length ? inputTimes[inputTimes.length - 1] : null;
  const activeSpanMs = firstInputMs !== null && lastInputMs !== null ? lastInputMs - firstInputMs : 0;
  const inputCount = pyIntOr(fieldMetrics.input_count, inputEvents.length);
  const deletionCount = pyInt(fieldMetrics.deletion_count);
  const revisionCount = pyIntOr(fieldMetrics.revision_count, largeJumps.length);
  const pauseCount = pyIntOr(
    fieldMetrics.pause_count,
    intervals.filter((gap) => gap >= FALLBACK_PAUSE_GAP_MS).length,
  );

  return {
    pipeline_version: PIPELINE_VERSION,
    field_name: fieldName,
    event_count: events.length,
    input_count: inputCount,
    first_input_latency_ms: firstInputMs,
    active_span_ms: activeSpanMs,
    final_length: finalLength,
    chars_per_minute: activeSpanMs > 0 ? pyRound((finalLength / activeSpanMs) * 60000, 3) : 0,
    inter_input_median_ms: intervals.length ? median(intervals) : 0,
    inter_input_p90_ms: percentile(intervals, 0.9),
    pause_count: pauseCount,
    max_pause_ms: pyIntOr(fieldMetrics.max_pause_ms, intervals.length ? Math.max(...intervals) : 0),
    pause_ratio: safeRatio(pauseCount, Math.max(intervals.length, 1)),
    deletion_ratio: safeRatio(deletionCount, Math.max(inputCount, 1)),
    revision_ratio: safeRatio(revisionCount, Math.max(inputCount, 1)),
    large_revision_count: largeJumps.length,
    paste_count: pyInt(fieldMetrics.paste_count),
    focus_count: pyInt(fieldMetrics.focus_count),
    blur_count: pyInt(fieldMetrics.blur_count),
  };
}

/**
 * Every field the telemetry names, in Python's `sorted()` order. Field names
 * are ASCII identifiers, where UTF-16 and code-point order agree.
 */
export function writingDynamicsForSession(
  fieldMetrics: Record<string, unknown> | null | undefined,
  rawEvents: WritingDynamicsEvent[] | null | undefined,
): Record<string, FieldDynamics> {
  const metrics = fieldMetrics && typeof fieldMetrics === "object" ? fieldMetrics : {};
  const events = Array.isArray(rawEvents) ? rawEvents : [];
  const names = new Set(Object.keys(metrics));
  for (const event of events) {
    if (event?.field_name) names.add(String(event.field_name));
  }
  const out: Record<string, FieldDynamics> = {};
  for (const name of [...names].sort()) {
    const value = metrics[name];
    const forField = value && typeof value === "object" && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
    out[name] = writingDynamicsForField(name, forField, events);
  }
  return out;
}

// ---------------------------------------------------------------------------
// Change against the student's own baseline: `writing_change_against_baseline`
// ---------------------------------------------------------------------------

export type WritingChangeDirection = "higher" | "lower";
export type WritingChange = { feature: WritingChangeFeature; direction: WritingChangeDirection };

export type WritingChangeOutcome = {
  pipeline_version: string;
  field_name: string;
  status: "not_enough_data" | "insufficient_input" | "within_baseline" | "observed";
  observed_days: number;
  required_days: number;
  current: Record<WritingChangeFeature, number>;
  baseline_provenance: BaselineProvenance;
  changes: WritingChange[];
  /** Present only when a comparison was made. Research record; never sent to an educator. */
  baseline?: Record<WritingChangeFeature, { mean: number; std: number }>;
  z_scores?: Record<WritingChangeFeature, number>;
  degenerate_features?: WritingChangeFeature[];
};

/** The comparable shape of a stored `writing_dynamics_for_field` output. */
export type ComparableDynamics = Partial<Record<WritingChangeFeature | "input_count", unknown>>;

function qualifies(features: ComparableDynamics | null | undefined): boolean {
  return pyInt(features?.input_count) >= MIN_FIELD_INPUTS;
}

function vectorOf(features: ComparableDynamics | null | undefined): Record<WritingChangeFeature, number> {
  const vector = {} as Record<WritingChangeFeature, number>;
  for (const name of WRITING_CHANGE_FEATURES) vector[name] = pyFloat(features?.[name]);
  return vector;
}

function dayVector(entries: ComparableDynamics[]): Record<WritingChangeFeature, number> | null {
  const vectors = entries.filter(qualifies).map(vectorOf);
  if (vectors.length === 0) return null;
  const mean = {} as Record<WritingChangeFeature, number>;
  for (const name of WRITING_CHANGE_FEATURES) {
    // Summed left to right, as Python's sum() does, so the two agree bit for bit.
    let total = 0;
    for (const vector of vectors) total += vector[name];
    mean[name] = total / vectors.length;
  }
  return mean;
}

/**
 * Compare one entry's journal-field dynamics with the student's own past.
 *
 * `historyDays` is one array per prior day, MOST RECENT FIRST. Days with no
 * qualifying entry are skipped and the window is the most recent
 * `RAMP_UP_DAYS` that qualify.
 */
export function writingChangeAgainstBaseline(
  current: ComparableDynamics,
  historyDays: ComparableDynamics[][],
): WritingChangeOutcome {
  const vectors: Array<Record<WritingChangeFeature, number>> = [];
  for (const day of historyDays) {
    const vector = dayVector(day ?? []);
    if (vector) vectors.push(vector);
    if (vectors.length >= RAMP_UP_DAYS) break;
  }
  const observed = vectors.length;
  const currentVector = vectorOf(current);
  const base = {
    pipeline_version: WRITING_CHANGE_VERSION,
    field_name: WRITING_CHANGE_FIELD,
    observed_days: observed,
    required_days: RAMP_UP_DAYS,
    current: currentVector,
  };

  if (observed < RAMP_UP_DAYS) {
    return { ...base, status: "not_enough_data", baseline_provenance: baselineProvenance("none", observed), changes: [] };
  }
  if (!qualifies(current)) {
    return { ...base, status: "insufficient_input", baseline_provenance: baselineProvenance("user", observed), changes: [] };
  }

  const stats = {} as Record<WritingChangeFeature, { mean: number; std: number }>;
  const zScores = {} as Record<WritingChangeFeature, number>;
  const degenerate: WritingChangeFeature[] = [];
  for (const name of WRITING_CHANGE_FEATURES) {
    const values = vectors.map((vector) => vector[name]);
    let total = 0;
    for (const value of values) total += value;
    const mean = total / values.length;
    let squares = 0;
    for (const value of values) squares += (value - mean) ** 2;
    const std = Math.max(Math.sqrt(squares / values.length), MIN_STD);
    stats[name] = { mean, std };
    zScores[name] = (currentVector[name] - mean) / std;
    if (values.every((value) => value === values[0])) degenerate.push(name);
  }

  // A feature that never moved across the window is reported as degenerate,
  // never as a change: its z-score is the change over a floor constant (#85).
  const reportable = WRITING_CHANGE_FEATURES.filter(
    (name) => !degenerate.includes(name) && Math.abs(zScores[name]) >= CHANGE_Z_THRESHOLD,
  ).sort(
    (a, b) =>
      Math.abs(zScores[b]) - Math.abs(zScores[a]) ||
      WRITING_CHANGE_FEATURES.indexOf(a) - WRITING_CHANGE_FEATURES.indexOf(b),
  );

  return {
    ...base,
    status: reportable.length ? "observed" : "within_baseline",
    baseline_provenance: baselineProvenance("user", observed),
    baseline: stats,
    z_scores: zScores,
    degenerate_features: degenerate,
    changes: reportable.map((feature) => ({ feature, direction: zScores[feature] > 0 ? "higher" : "lower" })),
  };
}

// ---------------------------------------------------------------------------
// What an educator may receive
// ---------------------------------------------------------------------------

/**
 * The evidence list an educator-visible observation carries, or null when there
 * is nothing to show.
 *
 * Feature and direction only. The z-score, the student's means and today's raw
 * values stay in `writing_features.baseline_comparison_json`, which educators
 * cannot read (RLS): a number about a named minor is exactly what
 * `docs/educator_display_policy.md` rule 1 withholds, and a "2.7σ" beside a
 * name reads as a severity however it is labelled.
 *
 * Null for every status except `observed`, and for an `observed` with no
 * changes — rule 2: an observation with no evidence is not displayed, so it is
 * not written either.
 */
export function educatorEvidence(outcome: WritingChangeOutcome): WritingChange[] | null {
  if (outcome.status !== "observed" || outcome.changes.length === 0) return null;
  return outcome.changes.map(({ feature, direction }) => ({ feature, direction }));
}

/**
 * Bucket stored feature rows into days, most recent first, for
 * `writingChangeAgainstBaseline`. `day` is the UTC calendar day, the same day
 * boundary `supabaseWriter` uses for snapshots and insights.
 */
export function historyDaysFromRows(
  rows: Array<{ day: string; features: ComparableDynamics }>,
  beforeDay: string,
): ComparableDynamics[][] {
  const byDay = new Map<string, ComparableDynamics[]>();
  for (const row of rows) {
    if (!row?.day || row.day >= beforeDay) continue;
    const bucket = byDay.get(row.day) ?? [];
    bucket.push(row.features);
    byDay.set(row.day, bucket);
  }
  return [...byDay.entries()].sort((a, b) => (a[0] < b[0] ? 1 : a[0] > b[0] ? -1 : 0)).map(([, entries]) => entries);
}
