"""Deterministic writing dynamics, and the change in them against a student's own past.

## Two implementations, one contract (#468)

This module used to run only on the FastAPI research path, which is local-only
and not deployed (ADR 0001, `docs/adr/0001-fastapi-production-boundary.md`).
Production is the Next.js route handler, which stored the telemetry these
functions read (`entry_fields`, `interaction_events`) and never analysed it — so
the landing page's claim that Blesc notices changes in how a student writes,
relative to their own past, had no code behind it where students actually
write.

Option B of #468 brings the analysis into production by porting it to
TypeScript (`frontend/src/lib/writingDynamics.ts`), the same arrangement
`baseline.ts` has with `baseline.py` and `safety-assessment.ts` with
`services/safety.py`. Both sides are pinned to
`sentra/shared/writing_dynamics_conformance.json`. The expected values in it are
generated by running THIS file (`scripts/generate_writing_dynamics_conformance.py`),
so a change here goes red in `tests/test_writing_dynamics_conformance.py` until
the fixture is regenerated deliberately, and the TS side then goes red until it
follows.

`writing_change_against_baseline` is new with #468. It is written here as well
as in TS so that the research path and production cannot disagree about what
"a change in how this student writes" means.

## What this does NOT do

It reads timing and lengths, never text. It does not infer a state of mind
from a pause: the output is "this entry's longest pause was longer than this
student's own last fourteen writing days", and the educator surface renders
that and nothing about what it might mean (`docs/educator_display_policy.md`).
"""

from __future__ import annotations

from math import sqrt
from statistics import median
from typing import Any, Dict, Iterable, List, Optional, Sequence

from .baseline import RAMP_UP_DAYS, baseline_provenance


PIPELINE_VERSION = "writing-dynamics-v1"


def _safe_ratio(numerator: float, denominator: float) -> float:
    return round(numerator / denominator, 6) if denominator else 0.0


def _percentile(values: List[int], percentile: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, round((len(ordered) - 1) * percentile)))
    return float(ordered[index])


def writing_dynamics_for_field(field_name: str, field_metrics: Dict[str, Any], raw_events: Iterable[Dict[str, Any]]) -> Dict[str, Any]:
    events = sorted(
        [event for event in raw_events if event.get("field_name") == field_name],
        key=lambda event: int(event.get("relative_ms") or 0),
    )
    input_events = [event for event in events if event.get("event_type") == "input"]
    input_times = [int(event.get("relative_ms") or 0) for event in input_events]
    intervals = [later - earlier for earlier, later in zip(input_times, input_times[1:]) if later >= earlier]
    large_jumps = [
        abs(int((event.get("metadata") or {}).get("delta") or 0))
        for event in input_events
        if abs(int((event.get("metadata") or {}).get("delta") or 0)) > 1
    ]
    final_length = int(input_events[-1].get("value_length") or field_metrics.get("char_count") or 0) if input_events else 0
    first_input_ms = input_times[0] if input_times else None
    last_input_ms = input_times[-1] if input_times else None
    active_span_ms = (last_input_ms - first_input_ms) if first_input_ms is not None and last_input_ms is not None else 0
    input_count = int(field_metrics.get("input_count") or len(input_events) or 0)
    deletion_count = int(field_metrics.get("deletion_count") or 0)
    revision_count = int(field_metrics.get("revision_count") or len(large_jumps) or 0)
    pause_count = int(field_metrics.get("pause_count") or len([gap for gap in intervals if gap >= 1500]) or 0)
    return {
        "pipeline_version": PIPELINE_VERSION,
        "field_name": field_name,
        "event_count": len(events),
        "input_count": input_count,
        "first_input_latency_ms": first_input_ms,
        "active_span_ms": active_span_ms,
        "final_length": final_length,
        "chars_per_minute": round((final_length / active_span_ms) * 60000, 3) if active_span_ms > 0 else 0.0,
        "inter_input_median_ms": float(median(intervals)) if intervals else 0.0,
        "inter_input_p90_ms": _percentile(intervals, 0.9),
        "pause_count": pause_count,
        "max_pause_ms": int(field_metrics.get("max_pause_ms") or max(intervals or [0])),
        "pause_ratio": _safe_ratio(pause_count, max(len(intervals), 1)),
        "deletion_ratio": _safe_ratio(deletion_count, max(input_count, 1)),
        "revision_ratio": _safe_ratio(revision_count, max(input_count, 1)),
        "large_revision_count": len(large_jumps),
        "paste_count": int(field_metrics.get("paste_count") or 0),
        "focus_count": int(field_metrics.get("focus_count") or 0),
        "blur_count": int(field_metrics.get("blur_count") or 0),
    }


def writing_dynamics_for_session(field_metrics: Dict[str, Any], raw_events: Iterable[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    field_names = set(field_metrics.keys())
    for event in raw_events:
        if event.get("field_name"):
            field_names.add(str(event["field_name"]))
    return {
        field_name: writing_dynamics_for_field(
            field_name,
            field_metrics.get(field_name, {}) if isinstance(field_metrics.get(field_name), dict) else {},
            raw_events,
        )
        for field_name in sorted(field_names)
    }


# ---------------------------------------------------------------------------
# Change against the student's own baseline (#468)
# ---------------------------------------------------------------------------

WRITING_CHANGE_VERSION = "writing-change-v1"

# The one field a baseline is kept for. The journal body is the only free-text
# field written every day; `first_recall_30` is a timed probe whose length is
# bounded by design, and `mood` / `event_categories` are selections.
WRITING_CHANGE_FIELD = "journal_entry"

# The features compared against the student's own history, and why each one:
#
#   pause_ratio       share of gaps between edits that were pauses: how often
#                     the student stopped while writing (「ためらいの間」)
#   max_pause_ms      the longest of those stops
#   deletion_ratio    edits that shortened the text, per edit: writing something
#                     and taking it back (「書き直し」)
#   chars_per_minute  final length over the active span: pace
#   final_length      how much was written
#
# `revision_ratio` is deliberately NOT here. The production collector
# (`telemetry.ts`) counts a revision on every resumption after a pause, so its
# revision_count equals its pause_count and revision_ratio is pause_ratio under
# another name. Comparing both would report one change twice.
#
# `large_revision_count` is not here either: it reads `metadata.delta`, which the
# production collector never sends, so it is zero on every production entry.
WRITING_CHANGE_FEATURES = (
    "pause_ratio",
    "max_pause_ms",
    "deletion_ratio",
    "chars_per_minute",
    "final_length",
)

# An entry with fewer edits than this on the journal field is not compared and
# does not count toward the baseline. A pasted or dictated entry has one or two
# edits and no pauses to speak of. An engineering floor, not a measured one.
MIN_FIELD_INPUTS = 5

# How far, in the student's own standard deviations, a feature must move before
# it is reported as a change. An engineering choice: nothing in this repository
# has measured how often a student's writing moves this far on an ordinary day,
# so this is the conventional "unusual for this person" line and is described as
# exactly that, not as a validated threshold (#468).
CHANGE_Z_THRESHOLD = 2.0

# Floor on the standard deviation, as in `estimate_baseline`.
MIN_STD = 0.01


def _as_int(value: Any) -> int:
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def _as_float(value: Any) -> float:
    try:
        return float(value or 0.0)
    except (TypeError, ValueError):
        return 0.0


def _plain_sum(values: Iterable[float]) -> float:
    """Left-to-right float addition, deliberately not `sum()`.

    Since Python 3.12 `sum()` of floats is compensated (Neumaier), and
    JavaScript's `+` is not. The difference is an ulp or two, which is enough to
    make `all(value == values[0])` — the degenerate-feature test — disagree
    between the two implementations on a day averaged from several entries.
    """
    total = 0.0
    for value in values:
        total += value
    return total


def _qualifies(features: Dict[str, Any]) -> bool:
    return _as_int(features.get("input_count")) >= MIN_FIELD_INPUTS


def _vector(features: Dict[str, Any]) -> Dict[str, float]:
    return {name: _as_float(features.get(name)) for name in WRITING_CHANGE_FEATURES}


def _day_vector(entries: Sequence[Dict[str, Any]]) -> Optional[Dict[str, float]]:
    """Mean of a day's qualifying entries, or None when it has none."""
    vectors = [_vector(features) for features in entries if _qualifies(features)]
    if not vectors:
        return None
    return {name: _plain_sum(v[name] for v in vectors) / len(vectors) for name in WRITING_CHANGE_FEATURES}


def writing_change_against_baseline(
    current: Dict[str, Any],
    history_days: Sequence[Sequence[Dict[str, Any]]],
) -> Dict[str, Any]:
    """Compare one entry's journal-field dynamics with the student's own past.

    `current` is the `writing_dynamics_for_field` output for this entry's
    journal field. `history_days` is one list per prior day, MOST RECENT FIRST,
    each holding that day's `writing_dynamics_for_field` outputs. Days with no
    qualifying entry are skipped; the window is the most recent `RAMP_UP_DAYS`
    qualifying days.

    Below `RAMP_UP_DAYS` there is no comparison at all, for the same reason as
    the graph baseline (#91): there is nothing honest to compare against.
    """
    vectors: List[Dict[str, float]] = []
    for day in history_days:
        vector = _day_vector(day)
        if vector is not None:
            vectors.append(vector)
        if len(vectors) >= RAMP_UP_DAYS:
            break
    observed = len(vectors)
    current_vector = _vector(current)

    result: Dict[str, Any] = {
        "pipeline_version": WRITING_CHANGE_VERSION,
        "field_name": WRITING_CHANGE_FIELD,
        "observed_days": observed,
        "required_days": RAMP_UP_DAYS,
        "current": current_vector,
    }

    if observed < RAMP_UP_DAYS:
        result.update(
            status="not_enough_data",
            baseline_provenance=baseline_provenance("none", observed),
            changes=[],
        )
        return result

    if not _qualifies(current):
        # The baseline exists; this entry is too short to compare against it.
        result.update(
            status="insufficient_input",
            baseline_provenance=baseline_provenance("user", observed),
            changes=[],
        )
        return result

    stats: Dict[str, Dict[str, float]] = {}
    z_scores: Dict[str, float] = {}
    degenerate: List[str] = []
    for name in WRITING_CHANGE_FEATURES:
        values = [vector[name] for vector in vectors]
        mean = _plain_sum(values) / len(values)
        std = max(sqrt(_plain_sum((value - mean) ** 2 for value in values) / len(values)), MIN_STD)
        stats[name] = {"mean": mean, "std": std}
        z_scores[name] = (current_vector[name] - mean) / std
        if all(value == values[0] for value in values):
            degenerate.append(name)

    # A feature that did not move across the whole window has no spread to be
    # unusual against: its "z-score" is the change divided by a floor constant.
    # It is recorded as degenerate rather than reported as a change (cf. #85).
    reportable = [
        name for name in WRITING_CHANGE_FEATURES
        if name not in degenerate and abs(z_scores[name]) >= CHANGE_Z_THRESHOLD
    ]
    reportable.sort(key=lambda name: (-abs(z_scores[name]), WRITING_CHANGE_FEATURES.index(name)))

    result.update(
        status="observed" if reportable else "within_baseline",
        baseline_provenance=baseline_provenance("user", observed),
        baseline=stats,
        z_scores=z_scores,
        degenerate_features=degenerate,
        changes=[
            {"feature": name, "direction": "higher" if z_scores[name] > 0 else "lower"}
            for name in reportable
        ],
    )
    return result
