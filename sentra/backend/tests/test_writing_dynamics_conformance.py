"""The backend half of the shared writing-dynamics contract (#468).

Production never ran `writing_dynamics.py`: it lives on the FastAPI research
path, which is not deployed (ADR 0001), while the Next.js route handler stored
the telemetry and analysed none of it. #468 option B ports the analysis to
TypeScript (`frontend/src/lib/writingDynamics.ts`) rather than deploying
FastAPI. That makes two implementations of one contract — the shape that
produced #106 — so both are pinned to
`sentra/shared/writing_dynamics_conformance.json`.

The expected values in that file were generated by running the functions tested
here (`scripts/generate_writing_dynamics_conformance.py`), so this suite is what
makes the fixture authoritative: if this side's arithmetic changes, this goes
red and the fixture must be regenerated deliberately, after which the TS side
goes red until it follows.
"""

import json
from pathlib import Path

import pytest

from app.analytics.baseline import RAMP_UP_DAYS
from app.analytics.writing_dynamics import (
    CHANGE_Z_THRESHOLD,
    MIN_FIELD_INPUTS,
    MIN_STD,
    PIPELINE_VERSION,
    WRITING_CHANGE_FEATURES,
    WRITING_CHANGE_FIELD,
    WRITING_CHANGE_VERSION,
    writing_change_against_baseline,
    writing_dynamics_for_session,
)

CONTRACT_PATH = Path(__file__).resolve().parents[2] / "shared" / "writing_dynamics_conformance.json"

TOLERANCE = 1e-9


@pytest.fixture(scope="module")
def contract() -> dict:
    assert CONTRACT_PATH.exists(), f"shared contract missing at {CONTRACT_PATH}"
    return json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))


def _close(actual, expected, path, failures):
    """Recursive comparison: numbers within TOLERANCE, everything else exactly."""
    if isinstance(expected, dict):
        if not isinstance(actual, dict) or set(actual) != set(expected):
            failures.append(f"{path}: keys differ: expected {sorted(expected)}, got {sorted(actual or {})}")
            return
        for key in expected:
            _close(actual[key], expected[key], f"{path}.{key}", failures)
    elif isinstance(expected, list):
        if not isinstance(actual, list) or len(actual) != len(expected):
            failures.append(f"{path}: expected {expected}, got {actual}")
            return
        for index, (got, want) in enumerate(zip(actual, expected)):
            _close(got, want, f"{path}[{index}]", failures)
    elif isinstance(expected, bool) or expected is None or isinstance(expected, str):
        if actual != expected:
            failures.append(f"{path}: expected {expected!r}, got {actual!r}")
    elif isinstance(expected, (int, float)):
        if not isinstance(actual, (int, float)) or abs(actual - expected) > TOLERANCE:
            failures.append(f"{path}: expected {expected}, got {actual}")
    else:
        failures.append(f"{path}: unexpected fixture type {type(expected)}")


def test_contract_constants_are_this_implementation(contract):
    assert contract["contract"] == "writing_dynamics"
    assert contract["pipeline_version"] == PIPELINE_VERSION
    assert contract["change_pipeline_version"] == WRITING_CHANGE_VERSION
    assert contract["change_field"] == WRITING_CHANGE_FIELD
    assert contract["change_features"] == list(WRITING_CHANGE_FEATURES)
    assert contract["ramp_up_days"] == RAMP_UP_DAYS
    assert contract["min_field_inputs"] == MIN_FIELD_INPUTS
    assert contract["change_z_threshold"] == CHANGE_Z_THRESHOLD
    assert contract["min_std"] == MIN_STD
    assert len(contract["dynamics_cases"]) >= 5
    assert len(contract["change_cases"]) >= 10


def test_every_dynamics_case(contract):
    failures = []
    for case in contract["dynamics_cases"]:
        session = case["input"]
        actual = writing_dynamics_for_session(session["field_metrics"], session["events"])
        _close(actual, case["expected"], case["name"], failures)
    assert not failures, "backend diverges from the shared contract:\n  " + "\n  ".join(failures)


def test_every_change_case(contract):
    failures = []
    for case in contract["change_cases"]:
        actual = writing_change_against_baseline(case["current"], case["history_days"])
        _close(actual, case["expected"], case["name"], failures)
    assert not failures, "backend diverges from the shared contract:\n  " + "\n  ".join(failures)


def test_rounding_is_half_even(contract):
    """The ties the fixture was built around, asserted by value.

    If someone "simplifies" a rounding call on either side, the tolerance in the
    case comparison would still catch it — this names what was being protected.
    """
    case = next(c for c in contract["dynamics_cases"] if c["name"] == "rounding_ties_half_even")
    journal = case["expected"]["journal_entry"]
    assert journal["chars_per_minute"] == 0.062
    assert journal["deletion_ratio"] == 0.007812

    percentile = next(c for c in contract["dynamics_cases"] if c["name"] == "percentile_index_half_even")
    assert percentile["expected"]["journal_entry"]["inter_input_p90_ms"] == 1600.0


def test_below_the_ramp_there_is_no_comparison(contract):
    """#91 for writing: no baseline, no z-score, no change, at any day short of fourteen."""
    case = next(c for c in contract["change_cases"] if c["name"] == "an_ordinary_day_is_within_baseline")
    for days in range(RAMP_UP_DAYS):
        outcome = writing_change_against_baseline(case["current"], case["history_days"][:days])
        assert outcome["status"] == "not_enough_data"
        assert outcome["changes"] == []
        assert "z_scores" not in outcome


def test_a_change_names_a_feature_and_a_direction_only(contract):
    """What an educator may receive carries no number (educator_display_policy rule 1)."""
    for case in contract["change_cases"]:
        for change in case["expected"]["changes"]:
            assert set(change) == {"feature", "direction"}
            assert change["feature"] in WRITING_CHANGE_FEATURES
            assert change["direction"] in {"higher", "lower"}
